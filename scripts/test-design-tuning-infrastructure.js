#!/usr/bin/env node
"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const root = path.resolve(__dirname, "..");
const context = { self: {}, window: {}, module: { exports: {} }, Object, Number, isFinite };
context.self = context.window = { document: {}, CoreUI: require(path.join(root, "client/js/ui/coreUi.js")) };
vm.createContext(context);
function load(file) { vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context); }
load("client/js/designTuning/designTuningParameterRegistry.js");
load("client/js/designTuning/designTuningStateStore.js");
load("client/js/designTuning/designTuningResolver.js");
load("client/js/ui/motionDefaults.js");
const registry = context.window.DesignTuningParameterRegistry;
const Store = context.window.DesignTuningStateStore;
const Resolver = context.window.DesignTuningResolver;
const MotionDefaults = context.window.MotionDefaults;
const parameters = Array.from(registry.list());
assert.deepStrictEqual(parameters.slice(0, 8).map(x => x.id), ["motion.curve.enter", "motion.curve.exit", "motion.curve.standard", "motion.curve.press", "motion.duration.spatialExpand", "motion.duration.spatialContract", "motion.duration.viewContentEnter", "motion.duration.viewContentExit"]);
assert.strictEqual(new Set(parameters.map(x => x.id)).size, parameters.length, "stable parameter IDs are unique");
parameters.forEach(parameter => { assert.ok(parameter.id && parameter.type && parameter.domain && parameter.canonicalSource && parameter.projection && parameter.resetScope); assert.ok(!parameter.id.startsWith("--"), "CSS property is not public ID"); });
assert.strictEqual(registry.get("motion.duration.spatialExpand").motionRole, "spatialMorphExpand");
assert.strictEqual(registry.get("motion.duration.spatialContract").motionRole, "spatialMorphContract");
assert.strictEqual(registry.validate("motion.curve.enter", { x1: 0, y1: -20, x2: 1, y2: 30 }).valid, true);
assert.strictEqual(registry.validate("motion.curve.enter", { x1: -1, y1: 0, x2: 1, y2: 1 }).valid, false);
assert.strictEqual(registry.validate("motion.duration.spatialExpand", 0).valid, false);
assert.strictEqual(registry.validate("motion.duration.spatialExpand", -1).valid, false);
const memory = { data: {}, getItem(k) { return this.data[k] || null; }, setItem(k, v) { this.data[k] = v; } };
memory.data[Store.storageKey] = JSON.stringify({ version: 1, overrides: { unknown: 4, "motion.duration.spatialExpand": 520, "motion.curve.enter": { x1: 2, y1: 1, x2: 0.3, y2: 1 } } });
const store = Store.create({ storage: memory, registry });
assert.deepStrictEqual(JSON.parse(JSON.stringify(store.load())), { "motion.duration.spatialExpand": 520 });
assert.strictEqual(memory.data["AEToolbox.appearance.v1"], undefined);
assert.strictEqual(memory.data["AEToolbox.settings.v1"], undefined);
const curve = { x1: 0.2, y1: 1.2, x2: 0.4, y2: 1 };
assert.strictEqual(store.setOverride("motion.curve.enter", curve), true); curve.x1 = 0.9;
assert.strictEqual(store.getOverride("motion.curve.enter").x1, 0.2, "store clones incoming curve");
const read = store.getOverride("motion.curve.enter"); read.x1 = 0.8;
assert.strictEqual(store.getOverride("motion.curve.enter").x1, 0.2, "store clones outgoing curve");
assert.strictEqual(store.setOverride("motion.duration.spatialExpand", Infinity), false);
let safe = true;
let cssDurationProjectionCount = 0;
const css = {};
const canonicalCss = { "--motion-curve-enter": "cubic-bezier(0.16, 1, 0.3, 1)", "--motion-curve-exit": "cubic-bezier(0.32, 0, 0.67, 0)", "--motion-curve-standard": "cubic-bezier(0.22, 1, 0.36, 1)", "--motion-curve-press": "cubic-bezier(0.2, 0, 0, 1)", "--space-surface-edge": "calc(16px * var(--ui-scale))", "--radius-section-card": "calc(22px * var(--ui-scale))", "--elevation-surface-shell": "0 8px 24px rgba(0,0,0,.2)" };
const resolver = Resolver.create({ registry, store, rootStyle: { setProperty(k,v) { css[k]=v; }, removeProperty(k) { delete css[k]; } }, readComputed: k => css[k] || canonicalCss[k] || ({ "--text-secondary": "rgba(246, 240, 223, 0.66)", "--text-tertiary": "rgba(246, 240, 223, 0.42)", "--field-surface": "rgba(5, 4, 3, 0.5)", "--registry-option-surface": "rgba(8, 7, 6, 0.68)", "--separator": "rgba(214, 178, 94, 0.16)", "--panel-border": "rgba(214, 178, 94, 0.22)", "--input-border": "rgba(214, 178, 94, 0.16)" }[k]), isProjectionSafe: () => safe, getCanonicalDuration: role => MotionDefaults.durations[role], parseShadow: context.window.CoreUI.parseShadowValue, serializeShadow: context.window.CoreUI.serializeShadowValue, parseColorAlpha: context.window.CoreUI.parseColorAlphaValue, serializeColorAlpha: context.window.CoreUI.serializeColorAlphaValue, onProjectionApplied: () => { cssDurationProjectionCount += 1; } });
resolver.initialize();
const shadow = context.window.CoreUI.parseShadowValue("0 12px 26px rgba(0, 0, 0, 0.34)");
assert.deepStrictEqual(JSON.parse(JSON.stringify(shadow)), { offsetX: 0, offsetY: 12, blur: 26, spread: 0, color: "#000000", alpha: 0.34 });
assert.strictEqual(context.window.CoreUI.serializeShadowValue(shadow), "0px 12px 26px rgba(0, 0, 0, 0.34)");
resolver.setOverride("elevation.floatingSurface", { offsetX: 1, offsetY: 13, blur: 27, spread: 0, color: "#000000", alpha: 0.35 });
assert.strictEqual(css["--elevation-floating-surface"], "1px 13px 27px rgba(0, 0, 0, 0.35)");
resolver.resetDomain("elevation");
assert.strictEqual(css["--elevation-floating-surface"], undefined);
resolver.setOverride("spacing.surface.edge", 20);
assert.strictEqual(css["--space-surface-edge"], "calc(20px * var(--ui-scale))", "typed spacing projects through semantic property");
assert.strictEqual(resolver.setOverride("radius.sectionCard", 12), false, "protected identity radius cannot project");
assert.strictEqual(css["--radius-section-card"], undefined);
resolver.resetDomain("spacing");
assert.strictEqual(css["--space-surface-edge"], undefined, "domain reset restores stylesheet canonical");
MotionDefaults.setDurationOverrideResolver((role, canonical) => resolver.resolveDuration(role, canonical));
assert.strictEqual(MotionDefaults.resolveDuration("spatialMorphExpand", 1.35), Math.round(520 * 1.35), "override precedes existing speed policy");
resolver.setOverride("motion.duration.actionFeedback", 210);
assert.strictEqual(MotionDefaults.resolveDuration("actionFeedback", 1.35), 210, "newly covered non-major duration resolves its override without major-view scaling");
assert.strictEqual(css["--motion-curve-enter"], "cubic-bezier(0.2, 1.2, 0.4, 1)");
safe = false;
const projectionCountBeforeUnsafeEdits = cssDurationProjectionCount;
resolver.setOverride("motion.curve.enter", { x1: 0.3, y1: 0, x2: 0.7, y2: 1 });
resolver.setOverride("motion.curve.enter", { x1: 0.4, y1: 0, x2: 0.6, y2: 1 });
assert.strictEqual(css["--motion-curve-enter"], "cubic-bezier(0.2, 1.2, 0.4, 1)", "running presentation keeps snapshot A");
safe = true; resolver.flushPendingProjection();
assert.strictEqual(css["--motion-curve-enter"], "cubic-bezier(0.4, 0, 0.6, 1)", "completion applies latest B");
assert.strictEqual(cssDurationProjectionCount, projectionCountBeforeUnsafeEdits + 1, "safe boundary refreshes existing CSS projection once with latest state");
resolver.resetParameter("motion.curve.enter");
assert.strictEqual(css["--motion-curve-enter"], undefined, "curve reset removes inline projection");
resolver.resetMotion();
assert.strictEqual(MotionDefaults.resolveDuration("spatialMorphExpand", 1), 480, "duration reset restores canonical");
resolver.setOverride("motion.duration.spatialExpand", 540);
assert.strictEqual(resolver.resolveDuration("spatialMorphExpand", 480), 540);
resolver.resetParameter("motion.duration.spatialExpand");
assert.strictEqual(resolver.resolveDuration("spatialMorphExpand", 540), 540, "duration promotion invariant");
canonicalCss["--motion-curve-enter"] = "cubic-bezier(0.4, 0, 0.6, 1)";
resolver.setOverride("motion.curve.enter", { x1: 0.4, y1: 0, x2: 0.6, y2: 1 }); resolver.resetParameter("motion.curve.enter");
assert.strictEqual(css["--motion-curve-enter"], undefined, "curve promotion removes override so promoted stylesheet wins");
assert.strictEqual(css["--motion-curve-enter"] || canonicalCss["--motion-curve-enter"], "cubic-bezier(0.4, 0, 0.6, 1)", "curve promotion invariant preserves computed value");
const evidence = resolver.getEvidence();
assert.strictEqual(evidence.scope, "all");
assert.strictEqual(resolver.getEvidence("spacing").scope, "spacing");
assert.ok(evidence.canonical && evidence.overrides && evidence.resolved && evidence.promotionPatch);
store.clearAll(); store.save();
assert.deepStrictEqual(JSON.parse(memory.data[Store.storageKey]), { version: 1, overrides: {} });
memory.data[Store.storageKey] = "{malformed";
assert.deepStrictEqual(JSON.parse(JSON.stringify(store.load())), {}, "malformed storage safely normalizes to empty overrides");
const main = fs.readFileSync(path.join(root, "client/js/main.js"), "utf8");
const index = fs.readFileSync(path.join(root, "client/index.html"), "utf8");
assert.ok(main.includes("initializeDesignTuning();") && main.indexOf("initializeDesignTuning();") < main.indexOf("SettingsState = window.SettingsStateAdapter.create"), "bootstrap does not depend on opening Settings");
assert.ok(main.includes("if (DesignTuning) DesignTuning.flushPendingProjection();"), "real animation completion flushes pending projection");
assert.ok(main.includes("onProjectionApplied: function () { MotionDefaults.applyCss(document.documentElement, motionScale); }"), "CSS durations consume the same tuning-before-speed resolution");
assert.ok(index.indexOf("designTuningParameterRegistry.js") < index.indexOf("designTuningStateStore.js") && index.indexOf("designTuningStateStore.js") < index.indexOf("designTuningResolver.js") && index.indexOf("designTuningResolver.js") < index.indexOf("main.js"));
console.log("Design Tuning infrastructure tests passed.");
