function verifyPointerInverse(index, targetInfluence, rect, pointerId) {
    var initialInfluence = 0.4;
    var initialSvgX = index === 1 ? 28 + initialInfluence * 172 : 372 - initialInfluence * 172;
    var targetSvgX = index === 1 ? 28 + targetInfluence * 172 : 372 - targetInfluence * 172;
    var toClientX = function (svgX) { return rect.left + svgX / 400 * rect.width; };
    var projection;
    field.svg.rect = rect;
    field.setValue({ x1: initialInfluence, y1: initialInfluence * 2, x2: 1 - initialInfluence, y2: 1 - initialInfluence * 2 });
    field.handles[index - 1].dispatch("pointerdown", { pointerId: pointerId, clientX: toClientX(initialSvgX) + 4, clientY: rect.top + rect.height / 2, shiftKey: false, preventDefault: function () {} });
    doc.dispatch("pointermove", { clientX: toClientX(targetSvgX) + 4, clientY: rect.top + rect.height / 2, shiftKey: false, preventDefault: function () {} });
    projection = CoreUI.bezierSpeedProjection(field.getValue());
    assert(Math.abs((index === 1 ? projection.startInfluence : projection.endInfluence) - targetInfluence) < 0.0001, (index === 1 ? "start" : "end") + " pointer inverse must round-trip " + targetInfluence);
    if (index === 2) assert(Math.abs(field.getValue().x2 - (1 - targetInfluence)) < 0.0001, "end Influence increase must decrease canonical x2");
    doc.dispatch("pointerup", {});
}
